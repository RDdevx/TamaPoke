#!/usr/bin/env python3
"""build_web.py - the build_web.sh step, in Python (all the other tools are).

What it does, in order:

  1. resolve the firmware version (--bump patch by default; --no-bump to keep
     it; --set-version X.Y for an exact one) and check that FW_VERSION in
     TamaPoke.ino and "version" in web/manifest.json agree (--set-version
     also fixes a disagreement)
  2. compile the sketch with arduino-cli (ESP32-S3, the board config from
     CLAUDE.md)
  3. (also keeps the "Firmware: X.Y" pill in web/index.html in step with the
     version - it is typed into the page, not read from the manifest)
  3. stage the four flash parts and the merged whole-flash image, and only
     after a successful compile publish them to web/firmware/ and bump
     FW_VERSION + the manifest version - a compile or staging failure leaves
     the tree as it was; a publishing failure is rolled back best effort
  4. build web/firmware/tamapoke.bin from the four parts at the offsets in
     web/manifest.json, so the manifest stays the single source of truth
  5. check that every region pak the web installer knows about is present in
     web/ (missing ones are listed as a warning - a region without its pak
     is a supported state, the installer just skips it)

Unlike the original build_web.sh, this does NOT regenerate the region paks -
the shipped ones (including galar/paldea from tools/galar_paldea/) are the
intended artifacts and are left untouched.

It never touches dex.h / moves.h / noart.h - those come from
tools/galar_paldea/gen_dex.py and must not be regenerated by the build.

Usage (from the project root, e.g. in an MSYS2 UCRT64 shell):

    python3 tools/build_web.py                    # build + bump patch version
    python3 tools/build_web.py --no-bump          # build, keep the version
    python3 tools/build_web.py --set-version 3.13 # build with an exact version
    python3 tools/build_web.py --bump minor       # 3.12 -> 3.13
    python3 tools/build_web.py --from-existing    # rebuild tamapoke.bin from
                                                  # the parts already in
                                                  # web/firmware/ (no compile)
    python3 tools/build_web.py --dry-run          # print the plan, write nothing

Options:
    --fqbn FQBN         board config (default: the ESP32-S3 build from CLAUDE.md)
    --boot-app0 PATH    explicit path to boot_app0.bin (default: searched in
                        the arduino-cli esp32 core)
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)          # the sketch root (TamaPoke.ino)
WEB = os.path.join(PROJECT, 'web')
FW_DIR = os.path.join(WEB, 'firmware')

DEFAULT_FQBN = ("esp32:esp32:esp32s3:CDCOnBoot=cdc,FlashSize=16M,"
                "PSRAM=opi,PartitionScheme=app3M_fat9M_16MB")

PAD = b'\xFF'          # inter-image padding, as the shipped tamapoke.bin uses


# --------------------------------------------------------------------------
# small helpers (explicit UTF-8 + newline preservation, for Windows/MSYS2)
# --------------------------------------------------------------------------

def read_text(path):
    with open(path, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def write_text(path, s):
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(s)


def read_json(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def write_json(path, obj):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(obj, f, indent=2)
        f.write('\n')


def fail(msg):
    sys.exit('error: ' + msg)


# --------------------------------------------------------------------------
# version handling
# --------------------------------------------------------------------------

def find_sketch():
    inos = [f for f in os.listdir(PROJECT) if f.endswith('.ino')]
    if len(inos) != 1:
        fail('expected exactly one .ino in %s, found: %s' % (PROJECT, inos))
    return inos[0]


def fw_version(src):
    m = re.search(r'#define FW_VERSION "([^"]+)"', src)
    if not m:
        fail('FW_VERSION not found in the sketch')
    return m.group(1)


def set_fw_version(src, new):
    src2 = re.sub(r'(#define FW_VERSION ")[^"]+(")',
                  r'\g<1>%s\g<2>' % new, src, count=1)
    if fw_version(src2) != new:
        fail('FW_VERSION rewrite failed')
    return src2


def valid_version(v):
    return re.fullmatch(r'\d+\.\d+', v) is not None


def bump(v, kind):
    major, minor = (int(x) for x in v.split('.'))
    if kind == 'major':
        return '%d.0' % (major + 1)
    return '%d.%d' % (major, minor + 1)


# --------------------------------------------------------------------------
# compile
# --------------------------------------------------------------------------

def find_arduino_cli():
    exe = shutil.which('arduino-cli')
    if not exe:
        fail('arduino-cli not on PATH - install it (scoop install arduino-cli '
             '/ choco install arduino-cli / github release exe)')
    return exe


def run(cmd, **kw):
    print('$', ' '.join(str(c) for c in cmd))
    r = subprocess.run([str(c) for c in cmd], **kw)
    if r.returncode != 0:
        fail('command failed (%d): %s' % (r.returncode, ' '.join(map(str, cmd))))


def arduino_data_dir(cli):
    """Locate arduino-cli's data directory (.../Arduino15)."""
    try:
        r = subprocess.run([cli, 'config', 'dump', '--json'],
                           capture_output=True, text=True, check=True)
        d = json.loads(r.stdout).get('directories', {}).get('data')
        if d and os.path.isdir(d):
            return d
    except Exception:
        pass
    home = os.path.expanduser('~')
    for cand in (os.path.join(home, '.arduino15'),
                 os.path.join(home, 'AppData', 'Local', 'Arduino15'),
                 os.path.join(home, 'Library', 'Arduino15')):
        if os.path.isdir(cand):
            return cand
    return None


def find_boot_app0(platform_dir, cli):
    """boot_app0.bin lives in the esp32 core: <platform>/tools/partitions/
    boot_app0.bin. Prefer the platform the board actually built against
    (parsed from the compile output); fall back to installed cores only
    when exactly one candidate exists."""
    if platform_dir:
        p = os.path.join(platform_dir, 'tools', 'partitions', 'boot_app0.bin')
        if os.path.isfile(p):
            return p
        print('warning: no boot_app0.bin in the platform used for the build '
              '(%s) - falling back to installed cores' % platform_dir)
    data = arduino_data_dir(cli)
    if not data:
        return None
    hw = os.path.join(data, 'packages', 'esp32', 'hardware', 'esp32')
    if not os.path.isdir(hw):
        return None
    cands = []
    for ver in os.listdir(hw):
        p = os.path.join(hw, ver, 'tools', 'partitions', 'boot_app0.bin')
        if os.path.isfile(p):
            cands.append(p)
    if len(cands) == 1:
        return cands[0]
    if len(cands) > 1:
        fail('several esp32 cores provide boot_app0.bin and the active '
             'platform could not be determined - pass --boot-app0 with one '
             'of: %s' % ', '.join(cands))
    return None


def compile_sketch(cli, fqbn, out_dir, sketch):
    """Compile and return (app, bootloader, partitions) plus the platform
    directory the board actually built against (from the verbose line
    "Using board '...' from platform in folder: <path>", which arduino-cli
    prints for every compile; the path may contain spaces)."""
    print('$ %s compile --verbose --fqbn %s --output-dir <tmp> .' % (cli, fqbn))
    r = subprocess.run(
        [cli, 'compile', '--verbose', '--fqbn', fqbn,
         '--output-dir', out_dir, '.'],
        cwd=PROJECT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stdout.write(r.stdout)
        sys.stderr.write(r.stderr)
        fail('compile failed (%d)' % r.returncode)
    m = re.search(r"from platform in folder: (.+)", r.stdout + r.stderr)
    platform = m.group(1).strip() if m else None
    files = sorted(os.listdir(out_dir))
    skip = ('.bootloader.bin', '.partitions.bin', '.merged.bin')
    apps = [f for f in files if f.endswith('.bin') and f != 'boot_app0.bin'
            and not f.endswith(skip)]
    boots = [f for f in files if f.endswith('.bootloader.bin')]
    parts = [f for f in files if f.endswith('.partitions.bin')]
    if len(boots) != 1 or len(parts) != 1:
        fail('ambiguous compile output - bootloader/partitions candidates: '
             '%s / %s (got: %s)' % (boots, parts, files))
    if sketch + '.bin' in apps:
        app = sketch + '.bin'
    elif len(apps) == 1:
        app = apps[0]
    else:
        fail('ambiguous app candidates (expected %s.bin): %s'
             % (sketch, apps))
    return (os.path.join(out_dir, app),
            os.path.join(out_dir, boots[0]),
            os.path.join(out_dir, parts[0]),
            platform)


# --------------------------------------------------------------------------
# parts + merged image
# --------------------------------------------------------------------------

def merged_image(manifest, part_blobs):
    """Merge the parts at the manifest's offsets - pure Python, no esptool.
    Confirmed byte-exact against the tamapoke.bin this project ships.
    part_blobs: {web-relative part path: bytes}."""
    builds = manifest.get('builds', [])
    if len(builds) != 1:
        fail('expected exactly one build in manifest.json')
    parts = builds[0].get('parts', [])
    missing = [p['path'] for p in parts if p['path'] not in part_blobs]
    if missing:
        fail('no built part for manifest entries: %s' % ', '.join(missing))
    image = bytearray()
    for part in parts:
        off = part['offset']
        if len(image) < off:
            image.extend(PAD * (off - len(image)))      # pad up to the offset
        elif len(image) > off:
            fail('part %s overlaps the previous one' % part['path'])
        image.extend(part_blobs[part['path']])
    return bytes(image)


PILL_RE = re.compile(r'(Firmware:\s*<b>)[^<]*(</b>)')


def pill_update(new_version):
    """The version pill in web/index.html is hardcoded text. Returns the new
    index.html text, or None (with a warning) if the pill is not found - a
    missing anchor must be loud, never a silent no-op."""
    path = os.path.join(WEB, 'index.html')
    if not os.path.isfile(path):
        print('warning: web/index.html not found - version pill not updated')
        return None
    src = read_text(path)
    if len(PILL_RE.findall(src)) != 1:
        print('warning: could not find exactly one "Firmware: <b>X.Y</b>" pill '
              'in web/index.html - update it by hand to %s' % new_version)
        return None
    return PILL_RE.sub(r'\g<1>%s\g<2>' % new_version, src, count=1)


def publish(staged, manifest, new_version):
    """staged: list of (web-relative path, bytes). Only called after the
    compile succeeded. Writes the files and rolls back anything already
    written if a write fails partway (best effort - restoration errors are
    reported, not hidden)."""
    written = []                      # (path, previous bytes or None)
    try:
        for rel, data in staged:
            path = os.path.join(WEB, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            written.append((path, open(path, 'rb').read()
                            if os.path.isfile(path) else None))
            with open(path, 'wb') as f:
                f.write(data)
            print('  wrote %-28s %8.1f KB' % (rel, len(data) / 1024))
        if new_version:
            mpath = os.path.join(WEB, 'manifest.json')
            written.append((mpath, open(mpath, 'rb').read()))
            m = dict(manifest)
            m['version'] = new_version
            write_json(mpath, m)
            print('  version -> %s (TamaPoke.ino + web/manifest.json)' % new_version)
            page = pill_update(new_version)
            if page is not None:
                ipath = os.path.join(WEB, 'index.html')
                written.append((ipath, open(ipath, 'rb').read()))
                write_text(ipath, page)
                print('  version pill -> %s (web/index.html)' % new_version)
    except BaseException:
        for path, old in reversed(written):        # best-effort rollback
            try:
                if old is None:
                    if os.path.isfile(path):
                        os.remove(path)
                else:
                    with open(path, 'wb') as f:
                        f.write(old)
            except OSError as e:
                print('warning: could not restore %s: %s' % (path, e),
                      file=sys.stderr)
        raise


# --------------------------------------------------------------------------
# region paks (read-only check)
# --------------------------------------------------------------------------

def check_region_paks():
    src = read_text(os.path.join(WEB, 'index.html'))
    m = re.search(r'const REGION_PAKS\s*=\s*\[([^\]]*)\]', src)
    if not m:
        print('warning: REGION_PAKS not found in web/index.html - skipping '
              'the pak check')
        return
    regions = re.findall(r"'([^']+)'", m.group(1))
    missing = [r for r in regions
               if not os.path.isfile(os.path.join(WEB, 'sprites-%s.pak' % r))]
    if missing:
        print('warning: no pak in web/ for: %s '
              '(the installer will skip those regions)' % ', '.join(missing))
    else:
        print('  all %d region paks present' % len(regions))


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ver = ap.add_mutually_exclusive_group()
    ver.add_argument('--bump', choices=['patch', 'minor', 'major'],
                     help='version bump style (default: patch)')
    ver.add_argument('--no-bump', action='store_true',
                    help='keep the version (still checked for consistency)')
    ver.add_argument('--set-version', metavar='X.Y',
                    help='build with this exact version')
    ap.add_argument('--fqbn', default=DEFAULT_FQBN)
    ap.add_argument('--boot-app0', metavar='PATH')
    ap.add_argument('--from-existing', action='store_true',
                    help='rebuild tamapoke.bin from the parts already in '
                         'web/firmware/ (no compile, no bump)')
    ap.add_argument('--dry-run', action='store_true',
                    help='print the plan, write nothing (does not compile)')
    args = ap.parse_args()

    sketch = find_sketch()
    ino_path = os.path.join(PROJECT, sketch)
    manifest = read_json(os.path.join(WEB, 'manifest.json'))
    fw = read_text(ino_path)

    # -- version resolution (no writes yet) ---------------------------------
    cur = fw_version(fw)
    mv = manifest.get('version')
    if mv != cur and args.set_version is None:
        fail('FW_VERSION (%s) and manifest version (%s) disagree - fix one '
             'by hand, or pass --set-version to force both' % (cur, mv))
    if args.from_existing and (args.bump or args.no_bump
                               or args.set_version is not None):
        fail('--from-existing does not change the version (it does not '
             'compile) - drop the version flag')
    if args.set_version is not None:
        if not valid_version(args.set_version):
            fail('--set-version must be MAJOR.MINOR, e.g. 3.13')
        new = args.set_version                    # same value = no-op, fine
    elif args.no_bump or args.from_existing:
        new = None
    else:
        new = bump(cur, args.bump or 'patch')

    # -- rebuild the merged image from the parts already on disk ------------
    if args.from_existing:
        if args.dry_run:
            print('dry run: would rebuild web/firmware/tamapoke.bin from '
                  'the parts already in web/firmware/')
            check_region_paks()
            return
        part_blobs = {}
        for p in manifest['builds'][0]['parts']:
            part_blobs[p['path']] = open(os.path.join(WEB, p['path']), 'rb').read()
        merged = merged_image(manifest, part_blobs)
        with open(os.path.join(FW_DIR, 'tamapoke.bin'), 'wb') as f:
            f.write(merged)
        print('  wrote web/firmware/tamapoke.bin  %8.1f KB (merged from '
              '%d existing parts)' % (len(merged) / 1024, len(part_blobs)))
        check_region_paks()
        print('done (merged image rebuilt from existing parts).')
        return

    # -- plan ----------------------------------------------------------------
    if args.dry_run:
        cli = shutil.which('arduino-cli') or '<arduino-cli (not found)>'
        print('dry run:')
        print('  $ %s compile --fqbn %s --output-dir <tmp> .' % (cli, args.fqbn))
        print('  write web/firmware/{app,bootloader,partitions,boot_app0}.bin')
        print('  write web/firmware/tamapoke.bin (merged at the manifest offsets)')
        if new and new != cur:
            print('  version %s -> %s (TamaPoke.ino + web/manifest.json)'
                  % (cur, new))
        check_region_paks()
        return

    cli = find_arduino_cli()

    # -- compile, stage everything, then publish with rollback ----------------
    if new is not None and new != cur:
        print('version: %s -> %s' % (cur, new))
    original_ino = fw
    try:
        if new is not None and new != cur:
            write_text(ino_path, set_fw_version(fw, new))
        with tempfile.TemporaryDirectory(prefix='tamapoke-build-') as out_dir:
            app, boot, parts, platform = compile_sketch(
                cli, args.fqbn, out_dir, sketch)
            boot_app0 = args.boot_app0 or find_boot_app0(platform, cli)
            if not boot_app0:
                fail('boot_app0.bin not found in the esp32 core - pass '
                     '--boot-app0 PATH (it lives at <arduino data>/packages/'
                     'esp32/hardware/esp32/<ver>/tools/partitions/'
                     'boot_app0.bin)')
            part_blobs = {
                'firmware/app.bin': open(app, 'rb').read(),
                'firmware/bootloader.bin': open(boot, 'rb').read(),
                'firmware/partitions.bin': open(parts, 'rb').read(),
                'firmware/boot_app0.bin': open(boot_app0, 'rb').read(),
            }
            merged = merged_image(manifest, part_blobs)
            staged = [(rel, part_blobs[rel]) for rel in
                      ('firmware/app.bin', 'firmware/bootloader.bin',
                       'firmware/partitions.bin', 'firmware/boot_app0.bin')]
            staged.append(('firmware/tamapoke.bin', merged))
        publish(staged, manifest, new)
    except BaseException:
        # a failed build leaves the tree as it was
        write_text(ino_path, original_ino)
        raise
    check_region_paks()
    print('done. flash from web/index.html (the installer picks up the new '
          'parts as they land).')


if __name__ == '__main__':
    main()
